package ru.endlesscode.mimic.impl.mythicmobs

import net.kyori.adventure.key.Key
import org.bukkit.entity.Player
import org.bukkit.inventory.ItemStack
import ru.endlesscode.mimic.internal.Log
import ru.endlesscode.mimic.items.ItemProvider
import java.util.concurrent.ConcurrentHashMap

/**
 * Item provider for MythicMobs items, including items of MythicCrucible.
 * Mythic IDs are lowercased and characters not allowed in item IDs are replaced with `_`:
 * `SkeletonKingSword` -> `skeletonkingsword`.
 * If several Mythic IDs become the same item ID, the one equal to the item ID is used, otherwise the first one.
 * Takes no payload. An item created for a player is generated by MythicMobs for this player.
 */
internal class MythicMobsItemProvider(
    private val mythicMobs: MythicMobsWrapper = MythicMobsWrapper(),
) : ItemProvider {

    private val reportedDuplicates = ConcurrentHashMap.newKeySet<String>()

    override val id: String = ID
    override val isEnabled: Boolean get() = mythicMobs.isEnabled

    override val allItems: Collection<String>
        get() {
            val idsByMimicId = mythicMobs.itemIds.groupBy(String::toMimicId)
            for ((mimicId, sameIds) in idsByMimicId) {
                if (sameIds.size > 1 && reportedDuplicates.add(mimicId)) {
                    val usedId = if (mimicId in sameIds) mimicId else sameIds.first()
                    Log.w("[MythicMobs] Items $sameIds have the same Mimic ID '$mimicId', only '$usedId' is used.")
                }
            }
            return idsByMimicId.keys.toList()
        }

    override fun hasItem(itemId: String): Boolean = findMythicId(itemId) != null

    override fun getItemId(item: ItemStack): String? = mythicMobs.getItemId(item)?.toMimicId()

    override fun createItem(itemId: String, amount: Int, player: Player?, payload: String?): ItemStack? {
        val mythicId = findMythicId(itemId) ?: return null
        return mythicMobs.createItem(mythicId, amount, player)
    }

    private fun findMythicId(itemId: String): String? =
        itemId.takeIf(mythicMobs::hasItem) ?: mythicMobs.itemIds.find { it.toMimicId() == itemId }

    companion object {
        const val ID: String = "mythicmobs"
    }
}

private fun String.toMimicId(): String = buildString {
    for (char in this@toMimicId.lowercase()) append(if (Key.allowedInValue(char)) char else '_')
}
